using System.Numerics;
using LPLK_AntiCamp;
int count=0;void Check(bool ok,string name){if(!ok)throw new Exception(name);count++;}
var s=new CampSettings();CampSettings.Validate(s);
var zero=Vector3.Zero;var look=new Vector2(20,0);
var clock=new CampClock(zero,Vector2.Zero);
Check(Enumerable.Range(0,1000).All(i=>clock.Step(i,zero,Vector2.Zero,s)==default),"Pure AFK stays out of AntiCamp for 1000 calls");
Check(!clock.Step(1000,zero,look,s).Punish,"First activity starts clock");
Check(Enumerable.Range(0,1000).All(_=>clock.Step(1001,zero,look,s)==default),"1000 timer calls cannot accelerate elapsed time");
Check(clock.Step(1026.9,zero,look,s)==default,"No early warning");
Check(clock.Step(1027,zero,look,s).Warn,"Warning five seconds before first slap (30+2)");
Check(!clock.Step(1029,zero,look,s).Warn,"Warning once");
Check(clock.Step(1030,zero,look,s).Announce,"Camp announced at 30 seconds");
Check(!clock.Step(1031.99,zero,look,s).Punish,"Grace respected");
Check(clock.Step(1032,zero,look,s).Punish,"First punishment at 32 seconds");
Check(!clock.Step(1033.99,zero,look,s).Punish,"Frequency respected");
Check(clock.Step(1034,zero,look,s).Punish,"Second interval");
Check(clock.Step(1100,zero,look,s).Punish,"One action after pause");
Check(!clock.Step(1100,zero,look,s).Punish,"No catch-up burst");
var lag=new CampClock(zero,Vector2.Zero);lag.Step(0,zero,look,s);
Check(lag.Step(40,zero,look,s).Warn,"Lag delivers warning first");
Check(!lag.Step(44.99,zero,look,s).Punish,"Lag still gives full five seconds");
Check(lag.Step(45,zero,look,s).Punish,"Punish after extended grace");
Check(!clock.HasMoved(new Vector3(49,0,0),50)&&clock.HasMoved(new Vector3(50,0,0),50),"Movement from fixed origin, not previous tick");
var origin=new CampClock(zero,Vector2.Zero);origin.Step(0,new Vector3(40,0,0),look,s);
Check(!origin.HasMoved(new Vector3(80,0,0),50),"Camp position starts at first activity");
Check(CampPolicy.AngleDistance(359,1)==2&&CampPolicy.AngleDistance(179,-179)==2,"Angle wrap does not fake activity");
Check(CampPolicy.Damage(17,s)==2&&CampPolicy.Damage(15,s)==0&&CampPolicy.Damage(10,s)==0,"Health reserve is not crossed");
Check(CampPolicy.Damage(4,s with{MinHealthReserve=0})==4,"Zero reserve permits lethal damage");
Check(CampPolicy.Exempt(2,false,true,false,false,s),"T may defend hostages");
Check(CampPolicy.Exempt(2,true,false,true,false,s),"T may defend planted bomb");
Check(CampPolicy.Exempt(3,true,false,false,false,s),"CT may defend bombsites");
Check(!CampPolicy.Exempt(2,true,false,false,false,s),"T must attack before plant");
Check(!CampPolicy.Exempt(3,false,true,false,false,s),"CT must rescue hostages");
var ct=s with{AllowCTCampBombMap=false};
Check(CampPolicy.Exempt(3,true,false,false,true,ct)&&!CampPolicy.Exempt(3,true,false,false,false,ct),"Dropped bomb exception separate");
Check(!CampPolicy.Exempt(3,false,false,false,true,ct),"Dropped state cannot create bomb map");
foreach(var invalid in new[]{s with{CampTime=0},s with{WarningSeconds=31},s with{PunishFrequency=0},s with{CampCheckRadius=double.NaN},s with{FirstPunishDelay=double.PositiveInfinity},s with{MinHealthReserve=-1}}){bool rejected=false;try{CampSettings.Validate(invalid);}catch(InvalidDataException){rejected=true;}Check(rejected,"Reject invalid config");}
Check(CampPolicy.NextMenuValue(97,5,100,0)==100,"Non-step HP reserve must not exceed valid maximum");
Check(CampPolicy.NextMenuValue(100,5,100,0)==0,"Reserve wraps only after maximum");
Check(CampPolicy.NextMenuValue(9.75,1,10,0)==10,"Fractional delay respects menu maximum");
Check(CampPolicy.NextMenuValue(60,1,10,1)==1,"File-configured interval enters menu range");
var noWarning=new CampClock(zero,Vector2.Zero);var quiet=s with{WarningSeconds=0,FirstPunishDelay=0};noWarning.Step(0,zero,look,quiet);
Check(noWarning.Step(29.999,zero,look,quiet)==default,"No early punishment without warning");
var atDeadline=noWarning.Step(30,zero,look,quiet);
Check(atDeadline.Punish&&atDeadline.Announce&&!atDeadline.Warn,"Disabled warning does not block punishment");
var reset=new CampClock(new Vector3(50,0,0),look);
Check(reset.Step(100,new Vector3(50,0,0),look,s)==default,"New life or movement state cannot inherit punishment");
var shortCamp=s with{CampTime=5,WarningSeconds=5,FirstPunishDelay=0};var early=new CampClock(zero,Vector2.Zero);early.Step(0,zero,look,shortCamp);
Check(early.Step(1,zero,look,shortCamp).Warn&&!early.Step(5,zero,look,shortCamp).Punish&&early.Step(6,zero,look,shortCamp).Punish,"Short camp still grants full warning window");
Console.WriteLine($"AntiCamp: {count} checks passed (AFK, real time, warning/grace, movement, objectives, health reserve, configuration, menu limits).");
